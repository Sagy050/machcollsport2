BEGIN;

ALTER TABLE public.athletes
  ADD COLUMN IF NOT EXISTS photo_path text,
  ADD COLUMN IF NOT EXISTS photo_consent text NOT NULL DEFAULT 'pending'
    CHECK (photo_consent IN ('pending', 'granted', 'declined'));

CREATE TABLE public.ads (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_name text NOT NULL,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  price text NOT NULL DEFAULT '',
  location text NOT NULL DEFAULT '',
  representative_name text NOT NULL,
  phone text NOT NULL,
  whatsapp text NOT NULL DEFAULT '',
  selling_when text NOT NULL DEFAULT '',
  image_path text,
  is_active boolean NOT NULL DEFAULT false,
  created_at bigint NOT NULL,
  updated_at bigint NOT NULL
);
CREATE INDEX ads_active_updated ON public.ads (is_active, updated_at DESC);
CREATE INDEX ads_club_lower ON public.ads (lower(club_name));
GRANT ALL ON public.ads TO service_role;
ALTER TABLE public.ads ENABLE ROW LEVEL SECURITY;

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES
  ('athlete-photos', 'athlete-photos', false, 524288, ARRAY['image/jpeg']),
  ('ads-images', 'ads-images', false, 524288, ARRAY['image/jpeg'])
ON CONFLICT (id) DO UPDATE SET
  public = false,
  file_size_limit = 524288,
  allowed_mime_types = ARRAY['image/jpeg'];

INSERT INTO public.audit (ts, username, action, detail)
VALUES (
  floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint,
  'migration',
  'ads.athlete_photos',
  'Added admin-managed marketplace ads and consent-gated athlete photo storage.'
);

COMMIT;
