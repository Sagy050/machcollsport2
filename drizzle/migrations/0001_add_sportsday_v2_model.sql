-- ---------- atomic helpers used by the server ----------
CREATE OR REPLACE FUNCTION public.sd_start_heat(_event integer, _heat integer, _at bigint, _now bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE started bigint; changed integer;
BEGIN
  UPDATE public.sd_events
     SET heat_starts = heat_starts || jsonb_build_object(_heat::text, _at),
         status = CASE WHEN status = 'scheduled' THEN 'live' ELSE status END,
         updated_at = _now
   WHERE id = _event AND NOT (heat_starts ? _heat::text);
  GET DIAGNOSTICS changed = ROW_COUNT;
  SELECT (heat_starts ->> _heat::text)::bigint INTO started FROM public.sd_events WHERE id = _event;
  RETURN jsonb_build_object('started_at', started, 'already', changed = 0);
END $$;

CREATE OR REPLACE FUNCTION public.sd_clear_heat_clock(_event integer, _heat integer, _now bigint)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  UPDATE public.sd_events SET heat_starts = heat_starts - _heat::text, updated_at = _now WHERE id = _event;
$$;

CREATE OR REPLACE FUNCTION public.sd_swap_results(_a integer, _b integer, _actor integer, _now bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE ra public.sd_entries; rb public.sd_entries;
BEGIN
  SELECT * INTO ra FROM public.sd_entries WHERE id = _a FOR UPDATE;
  SELECT * INTO rb FROM public.sd_entries WHERE id = _b FOR UPDATE;
  UPDATE public.sd_entries SET performance = rb.performance, perf_value = rb.perf_value, status = rb.status, updated_by = _actor, updated_at = _now WHERE id = _a;
  UPDATE public.sd_entries SET performance = ra.performance, perf_value = ra.perf_value, status = ra.status, updated_by = _actor, updated_at = _now WHERE id = _b;
END $$;

REVOKE EXECUTE ON FUNCTION public.sd_start_heat(integer, integer, bigint, bigint) FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.sd_clear_heat_clock(integer, integer, bigint) FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.sd_swap_results(integer, integer, integer, bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sd_start_heat(integer, integer, bigint, bigint) TO service_role;
GRANT EXECUTE ON FUNCTION public.sd_clear_heat_clock(integer, integer, bigint) TO service_role;
